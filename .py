import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

st.set_page_config(page_title="BiciDatos", layout="wide")

if "df_bici" not in st.session_state:
    st.session_state["df_bici"] = None

def obtener_datos_filtrados():
    df = st.session_state["df_bici"].copy()

    usuario = st.session_state["filtro_usuario"]
    if usuario == "Todos":
        df["alquileres"] = df["alquileres_total"]
    elif usuario == "Ocasionales":
        df["alquileres"] = df["alquileres_ocasionales"]
    else:
        df["alquileres"] = df["alquileres_registrados"]

    dia = st.session_state["filtro_dia"]
    if dia != "Todos":
        df = df[df["tipo_dia"] == dia]

    hora_ini, hora_fin = st.session_state["filtro_horas"]
    df = df[(df["hora"] >= hora_ini) & (df["hora"] <= hora_fin)]

    return df

def pagina_explorar():
    st.title("Explorar los datos")

    archivo = st.file_uploader("Selecciona bicicletas_listas.csv", type=["csv"])

    if st.button("Cargar datos"):
        if archivo is not None:
            df = pd.read_csv(archivo, encoding="utf-8-sig", parse_dates=["fecha"])
            st.session_state["df_bici"] = df
            st.success(f"{len(df):,} registros cargados.")
        else:
            st.warning("Por favor, selecciona el archivo bicicletas_listas.csv antes de presionar el botón.")

    if st.session_state["df_bici"] is None:
        st.info("Selecciona el archivo bicicletas_listas.csv y pulsa 'Cargar datos' para comenzar.")
        return

    df = obtener_datos_filtrados()

    total_alquileres = int(df["alquileres"].sum())
    promedio_hora = df["alquileres"].mean() if len(df) > 0 else 0.0

    col1, col2 = st.columns(2)
    col1.metric("Total de alquileres", f"{total_alquileres:,}".replace(",", "."))
    col2.metric("Promedio por hora observada", f"{promedio_hora:,.1f}".replace(",", "X").replace(".", ",").replace("X", "."))

    tab_grafico, tab_datos = st.tabs(["Gráfico diario", "Datos"])

    with tab_grafico:
        if len(df) > 0:
            df_diario = df.groupby("fecha", as_index=False)["alquileres"].sum()

            fig, ax = plt.subplots(figsize=(8, 3.8))
            ax.plot(df_diario["fecha"], df_diario["alquileres"], color="#197A8D", linewidth=1.2)
            ax.set_xlabel("Fecha")
            ax.set_ylabel("Alquileres por día")
            ax.set_ylim(bottom=0)
            ax.grid(axis="y", linestyle="-", alpha=0.3)
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
            st.pyplot(fig)
            st.caption("Cada total incluye las horas que conservan los filtros.")
        else:
            st.warning("No hay registros que coincidan con los filtros seleccionados.")

    with tab_datos:
        st.dataframe(df, use_container_width=True, hide_index=True)

        csv_datos = df.to_csv(index=False).encode("utf-8-sig")
        st.download_button(
            label="Descargar datos filtrados",
            data=csv_datos,
            file_name="bicicletas_filtradas.csv",
            mime="text/csv"
        )

        st.write("Fanaee-T, H. (2013). Bike Sharing. UCI. DOI 10.24432/C5W894. CC BY 4.0.")

        st.link_button(
            label="Consultar la fuente en UCI",
            url="https://archive.ics.uci.edu/dataset/275/bike+sharing+dataset"
        )

def pagina_comparar():
    st.title("Comparar horarios")

    if st.session_state["df_bici"] is None:
        st.info("Primero debes cargar los datos en la página 'Explorar los datos'.")
        return

    df = obtener_datos_filtrados()

    color_barras = st.color_picker("Color de las barras", "#197A8D")

    if len(df) > 0:
        df_horas = df.groupby("hora", as_index=False)["alquileres"].mean()
        df_horas.rename(columns={"alquileres": "promedio_alquileres"}, inplace=True)

        fig, ax = plt.subplots(figsize=(8, 3.8))
        ax.bar(df_horas["hora"], df_horas["promedio_alquileres"], color=color_barras, width=0.7)
        ax.set_xlabel("Hora del día")
        ax.set_ylabel("Alquileres por hora observada")
        ax.set_xticks(range(0, 24, 2))
        ax.grid(axis="y", linestyle="-", alpha=0.3)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        st.pyplot(fig)

        if st.checkbox("Mostrar tabla de promedios"):
            tabla_mostrar = df_horas.copy()
            tabla_mostrar["promedio_alquileres"] = tabla_mostrar["promedio_alquileres"].round(2)
            st.dataframe(tabla_mostrar, use_container_width=True, hide_index=True)

        st.markdown("---")

        limite = st.number_input(
            "Límite de alquileres por hora",
            min_value=0,
            value=250,
            step=10
        )

        superan_limite = df_horas[df_horas["promedio_alquileres"] > limite]
        cantidad_superan = len(superan_limite)
        total_horas_datos = len(df_horas)

        st.metric(
            label="Horarios con promedio mayor que el límite",
            value=f"{cantidad_superan}/{total_horas_datos}"
        )

        if cantidad_superan > 0:
            lista_horas = [f"{int(h):02d}:00" for h in superan_limite["hora"]]
            st.write(f"**Horarios:** {', '.join(lista_horas)}.")
        else:
            st.write("**Horarios:** Ninguno.")
    else:
        st.warning("No hay registros que coincidan con los filtros seleccionados.")

pag_explorar = st.Page(pagina_explorar, title="Explorar los datos")
pag_comparar = st.Page(pagina_comparar, title="Comparar horarios")

pg = st.navigation([pag_explorar, pag_comparar])

with st.sidebar:
    st.title("BiciDatos")

    st.selectbox(
        "Tipo de usuario",
        ["Todos", "Ocasionales", "Registrados"],
        key="filtro_usuario"
    )

    st.radio(
        "Tipo de día",
        ["Todos", "Laborable", "No laborable"],
        key="filtro_dia"
    )

    st.slider(
        "Horas del día",
        min_value=0,
        max_value=23,
        value=(0, 23),
        key="filtro_horas"
    )

pg.run()